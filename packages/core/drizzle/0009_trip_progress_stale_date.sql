-- Одноразова правка даних, не схеми.
--
-- Чернетка дня на телефоні жила ~20 годин і при відкритті застосунку
-- віддавала свою дату. Бригадир увечері 02.09 відкрив заплановану адміном
-- поїздку, чернетка збереглася з датою 02.09, а виїхав він уранці 03.09 —
-- і всі точки «де бригада» пішли на 02.09. Через це «Поточні поїздки»
-- показували сьогоднішню бригаду вчорашнім днем.
--
-- Причину виправлено в коді (чернетка тримає свою дату лише після виїзду),
-- але вже записані рядки треба перенести.
--
-- Умова навмисно вузька: беруться лише рядки з датою 02.09, ЗАПИСАНІ вже
-- після півночі за Києвом (21:00 UTC 02.09). Справжні вчорашні точки
-- писалися вдень 02.09 і під неї не потрапляють. Якщо таких рядків немає —
-- запит нічого не робить.
--
-- trip_progress — звіт для екрана адміна, з нього нічого не рахується
-- (див. schema.ts), тож на зарплату й БУХЗВІТ ця правка не впливає ніяк.
UPDATE trip_progress
SET date = '2026-09-03'
WHERE date = '2026-09-02'
  AND updated_at >= TIMESTAMP '2026-09-02 21:00:00';
