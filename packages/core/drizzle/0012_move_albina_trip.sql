-- Одноразова правка даних: поїздку Левченко Альбіни, яку телефон записав
-- учорашнім днем, перенести на 03.09.
--
-- Попередні спроби відбирали рядки за станом («резерв досі тримається») або
-- за часом запису («після півночі»). Обидва критерії залежать від того, що
-- бригада робить прямо зараз: варто їй повернутись на базу — і резерв уже не
-- останній, умова не спрацьовує. Тому тут якір нерухомий.
--
-- Якір — її ОСТАННІЙ резерв авто за 02.09. Пізніше за сьогоднішню поїздку
-- вона нічого забронювати не могла, тож усе, що записане від цієї миті й
-- далі, належить саме їй і саме сьогоднішньому дню. Усе раніше — це вчорашні
-- Рікка й Карась, вони лишаються на місці.
--
-- RTS_SAVE не переноситься: її вчорашні здані поїздки вже пішли в БУХЗВІТ під
-- 02.09, і зрушити їх означало б розсинхронізувати базу зі звітом бухгалтера.
WITH me AS (
  SELECT tg_id FROM users WHERE pib LIKE 'Левченко Альбіна%' LIMIT 1
),
anchor AS (
  SELECT max(e.ts) AS ts
  FROM events e, me
  WHERE e.date = '2026-09-02'
    AND e.type = 'RTS_RESERVE_CAR'
    AND e.foreman_tg_id = me.tg_id
)
UPDATE events e
SET date = '2026-09-03'
FROM me, anchor
WHERE e.date = '2026-09-02'
  AND e.foreman_tg_id = me.tg_id
  AND e.type <> 'RTS_SAVE'
  AND anchor.ts IS NOT NULL
  AND e.ts >= anchor.ts;
