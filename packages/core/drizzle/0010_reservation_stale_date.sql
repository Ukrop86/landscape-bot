-- Одноразова правка даних, продовження 0009.
--
-- Картка «У ДОРОЗІ ЗАРАЗ» на екрані адміна будується НЕ з trip_progress, а з
-- подій резерву авто й людей: береться остання подія по кожному авто за цю
-- дату (див. GET /admin/overview). 0009 переніс точки стрічки, але самі
-- резерви лишились на 02.09 — тому бригада зникла зі стрічки вчорашнього дня
-- і не зʼявилась у сьогоднішньому.
--
-- Умова та сама, що й у 0009: подія з датою 02.09, СТВОРЕНА вже після
-- півночі за Києвом (21:00 UTC). Резерв, створений сьогодні, але записаний
-- учорашнім днем, може взятися лише зі старої чернетки на телефоні — інших
-- шляхів туди немає.
--
-- Типи навмисно обмежені резервами. RTS_SAVE не чіпаємо: зданий день з
-- датою в минулому — це нормальний випадок «внести день заднім числом», і
-- переносити його було б помилкою.
UPDATE events
SET date = '2026-09-03'
WHERE date = '2026-09-02'
  AND ts >= TIMESTAMP '2026-09-02 21:00:00'
  AND type IN ('RTS_RESERVE_CAR', 'RTS_RESERVE_PEOPLE');
