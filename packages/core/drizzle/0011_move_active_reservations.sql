UPDATE events
SET date = '2026-09-03'
WHERE date = '2026-09-02'
  AND type = 'RTS_RESERVE_CAR'
  AND event_id IN (
    SELECT DISTINCT ON (car_id) event_id
    FROM events
    WHERE date = '2026-09-02'
      AND car_id IS NOT NULL
      AND type IN ('RTS_RESERVE_CAR', 'RTS_CAR_RETURN', 'RTS_SAVE', 'RTS_RESERVE_CANCEL')
    ORDER BY car_id, ts DESC
  );

