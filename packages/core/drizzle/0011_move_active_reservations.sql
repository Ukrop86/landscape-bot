-- Люди того самого бригадира, заброньовані не раніше за це авто. Умова
-- `p.ts >= c.ts` відсікає резерви його ж попередніх, уже зданих поїздок за цю
-- дату: вони записані раніше. Бригадирів, чиї резерви щойно переїхали, тут
-- видно за тим, що їхня подія вже має дату 03.09.
UPDATE events p
SET date = '2026-09-03'
WHERE p.date = '2026-09-02'
  AND p.type = 'RTS_RESERVE_PEOPLE'
  AND EXISTS (
    SELECT 1
    FROM events c
    WHERE c.date = '2026-09-03'
      AND c.type = 'RTS_RESERVE_CAR'
      AND c.foreman_tg_id = p.foreman_tg_id
      AND p.ts >= c.ts
  );
