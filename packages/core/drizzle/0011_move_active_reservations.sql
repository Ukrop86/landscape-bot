-- Одноразова правка даних. Третя спроба, і перші дві варто пояснити.
--
-- 0009 і 0010 відбирали рядки за часом запису: «датоване 02.09, але записане
-- вже після півночі». Для точок стрічки це спрацювало — вони писалися вранці
-- 03.09. Для резервів ні: бригадир відкрив заплановану адміном поїздку ще
-- ввечері 02.09 і вже тоді вибрав авто й людей, тож резерв записався до
-- півночі й під умову не потрапив.
--
-- Тому тут критерій не часовий, а той самий, яким сам застосунок вирішує, чи
-- авто ще в дорозі (див. CAR_RELEASE_TYPES у routes/roadTimesheet.ts):
-- береться ОСТАННЯ подія по кожному авто за 02.09, і рядок переноситься лише
-- якщо ця остання подія — резерв. У кого день зданий (RTS_SAVE) або авто
-- повернуте, остання подія інша, і такий запис не зачепиться за визначенням.
--
-- trip_progress уже перенесено в 0009 — тут його не чіпаємо, інакше поїде й
-- справжня вчорашня точка, яка законно лишилась на 02.09.

